"""EnO run 2026: 1D polariton waveguides for single-shot space-time vortices
(tep_polariton_gpe_code/projects/time_dependent/waveguide_space_time_vortices).

One write field per chip, built like the stretched-honeycomb field (stretched_honeycomb.py): the same left
column (2024 overlap-series dimers, 2024 50 x 50 um planar mesa, chip x/y index labels with the 2024 arrows),
the devices to the right, one grid ctl (vwg_grid.ctl) that writes the field grid with the field x/y labels,
and a jdf placing the exported .v30 once.

Devices: straight rectangular waveguides along y (guide axis of the GPE model, model_definitions.py:
`_rectangular_waveguide_mask`, |x| <= W/2, |y| <= L/2). Exposed area = mesa = the guide stripe (EnO convention:
drawn = unetched mesa; the etched surroundings are V higher in photon energy). Each guide is one exact RECT in
integer nm (no rasterisation); widths and lengths are multiples of the 25 nm raster of the other EnO structures.

Parameters (sources in the block below): width series around W* of the 04 width x depth scan, lengths >= 250 um
(user 2026-10-13: reflections at the guide end cause self-interference in the experiment), one etch depth per wafer.
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..")))
import eno_tools as T  # noqa: E402
from stretched_honeycomb import (  # noqa: E402  same references, numbers and arrows as the honeycomb field
    LEFT_X0, NUMBERS_SHIFT, place, reference_structures, shifted_numbers)

SYSTEM = "wg"
CHIP = "vwg_field"

# --- design parameters -------------------------------------------------------------------------------
# Source: tep_polariton_gpe_code/.../waveguide_space_time_vortices/04_layout_width_depth_scan.py, results
# 04_width_depth_scan_20261013_212543 (E_X 1.4707 eV, Rabi 4.2 meV, m_c 3.2e-5, m_X 0.2). The gap from the transverse
# ground mode to the next state peaks at W* = 1.6 um (mesa detuning -1.886 Rabi = -7.92 meV, user 2026-10-12),
# 1.5 um (-2 Rabi) and 1.2 um (-3 Rabi) at 18 meV, and saturates with depth (18 meV within 1-2 % of 22 meV).
# Series, copies and pitch are a proposal (layout logistics, not physics): confirm with the user.
DEPTH_MEV = 18.0                                   # photon confinement the widths are designed for (03, user 10-12)
WIDTHS_NM = (1000, 1200, 1400, 1600, 1800, 2000, 3000)  # W* range over -1.9...-3 Rabi + 2 um (03) + 3 um (README max)
# user 2026-10-13: "make the waveguides at least 250um long" (end reflections interfere in the experiment). Two rows
# of >= 250 um do not fit the 500 um field: one row, top-aligned; per width one guide of each length, 450 um = the
# longest that fits with its label
LENGTHS_NM = (250_000, 350_000, 450_000)
GUIDE_PITCH_NM = 19_000                            # centre-to-centre within the row (>= 16 um etched gap)

GRID_NX, GRID_NY = 3, 2  # field copies in vwg_grid.ctl (user adjusts; keep small for ECP checks)
STREET_UM = 50           # free space between neighbouring fields (pitch = 500 + 50 um)

GRID_X0 = 80_000         # left edge of the first guide column (right of the reference column, x <= 61.75 um)
GRID_TOP = 490_000       # top of the guide row


def guide(W, L):
    """One straight guide along y: exact rect (0, 0, W, L), local nm coordinates."""
    if W % T.PIXEL_NM or L % T.PIXEL_NM:
        raise ValueError(f"W {W} / L {L} nm not on the {T.PIXEL_NM} nm raster")
    name = f"w{W / 1000:.3f}_l{L // 1000:03d}".replace(".", "p")
    return {"name": name, "system": SYSTEM, "structures": [("", np.array([[0, 0, W, L]], dtype=np.int64), None)],
            "params": {"width_nm": W, "length_nm": L, "depth_design_meV": DEPTH_MEV, "guide_axis": "y"}}


def field_layout():
    devs, label, x = [], 1, GRID_X0
    for W in WIDTHS_NM:
        for L in LENGTHS_NM:
            # centre-to-centre pitch: place the guide left edge at (column centre - W/2)
            xc = x + GUIDE_PITCH_NM / 2
            devs.append(place(guide(W, L), int(round(xc - W / 2)), GRID_TOP, str(label)))
            label += 1
            x += GUIDE_PITCH_NM
    dimers, mesa, arrows = reference_structures()
    devs.append(place(dimers, LEFT_X0, GRID_TOP, None))  # no device numbers on references (as honeycomb field)
    devs.append(place(mesa, LEFT_X0, GRID_TOP - 75_000, None))
    devs.append(arrows)
    right = max(T.dev_bbox(d)[2] + d["pos"][0] for d in devs if d.get("system") == SYSTEM)
    bottom = min(d["label_pos"][1] for d in devs if d.get("system") == SYSTEM)
    if right > T.FIELD_NM - 10_000 or bottom < 10_000:
        raise RuntimeError(f"guides do not fit the field: right edge {right} nm, lowest label {bottom} nm")
    return devs


HEADER = [
    "Etch and overgrow 2026, 1D polariton waveguides for single-shot space-time vortices",
    "generated by pattern_creator/projects/eno_run_2026/vortex_waveguides.py",
    f"design etch depth {DEPTH_MEV:g} meV photon confinement; widths {', '.join(f'{w / 1000:g}' for w in WIDTHS_NM)} um",
    f"lengths {', '.join(f'{l // 1000}' for l in LENGTHS_NM)} um per width (one top-aligned row; user: >= 250 um), "
    f"pitch {GUIDE_PITCH_NM / 1000:g} um, guide axis y",
    "units nm; exposed area = mesa (guide stripe); exact RECTs, I 16, C 100 (as 2024/2026 EnO structures)",
    "left column: 2024 overlap-series dimers, 2024 50 x 50 um mesa, chip numbers + arrows (as shc_field)",
    "parameters in vwg_field_devices.csv",
]


if __name__ == "__main__":
    out = os.path.join(HERE, "ecp_layout", "vortex_waveguides")
    info = T.write_chip(out, CHIP, [field_layout()], HEADER, write_ctl=False,
                        numbers_box=(NUMBERS_SHIFT[0] + 20_000, NUMBERS_SHIFT[1],
                                     NUMBERS_SHIFT[0] + 52_000, NUMBERS_SHIFT[1] + 60_000))
    shifted_numbers(os.path.join(HERE, "inputs", "numbers_xy.pat"), os.path.join(out, "numbers_vwg.pat"),
                    *NUMBERS_SHIFT)
    pitch = int(T.FIELD_NM / 1000 + STREET_UM)
    T.grid_ctl(os.path.join(out, "vwg_grid.ctl"), CHIP, info["structures"][0], GRID_NX, GRID_NY, pitch, pitch,
               header=HEADER, numbers_file="numbers_vwg")
    dwells, incs = T.pat_dwells(os.path.join(out, f"{CHIP}.pat"), os.path.join(out, "numbers_vwg.pat"))
    if len(incs) != 1:
        raise RuntimeError(f"mixed increments {incs}: RESIST/MODULAT rule needs one increment")
    T.job_jdf(os.path.join(out, "vwg_grid.jdf"), "vwg_grid", dwells, increment=incs.pop())
    print(f"{CHIP}: {len(info['devices'])} devices in one 500 um write field; vwg_grid.ctl: "
          f"{GRID_NX} x {GRID_NY} fields at {pitch} um pitch")
    for r in info["devices"]:
        print(f"  {r['label']:>3} {r['structure']:<36} {r['width_um']:7.3f} x {r['height_um']:7.3f} um  "
              f"centre ({r['x_centre_um']:7.2f}, {r['y_centre_um']:7.2f}) um")
